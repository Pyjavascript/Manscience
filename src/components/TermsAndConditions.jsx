// Terms & Conditions Modal Component
function TermsModal({ selectedTab, onClose }) {
  const containerRef = useRef(null);
  const [scrollPercentage, setScrollPercentage] = useState(0);
  const [isOverflowing, setIsOverflowing] = useState(false);

  // 2. Add useEffect to check for overflow on mount and tab change
  useEffect(() => {
    const checkOverflow = () => {
      if (containerRef.current) {
        setIsOverflowing(
          containerRef.current.scrollHeight > containerRef.current.clientHeight,
        );
      }
    };
    checkOverflow();
    window.addEventListener("resize", checkOverflow);
    return () => window.removeEventListener("resize", checkOverflow);
  }, [selectedTab]);

  const handleScroll = () => {
    const container = containerRef.current;
    if (!container) return;

    const totalScrollableHeight =
      container.scrollHeight - container.clientHeight;
    if (totalScrollableHeight > 0) {
      const scrolled = (container.scrollTop / totalScrollableHeight) * 100;
      setScrollPercentage(scrolled);
    }
  };

  return (
    <div className="w-full mx-auto p-5 sm:p-8 lg:p-[40px] bg-[#FAF4E8] rounded-[34px] sm:rounded-[36px] manrope relative transition-all duration-300 ">
      {/* Header */}
      <div className="flex justify-between items-start mb-3">
        <div>
          <h2 className="text-[22px] sm:text-[28px] lg:text-[34px] font-medium text-[#B77145] leading-tight">
            Terms and Conditions
          </h2>
          <p className="text-[14px] md:text-[16px] text-[#B77145] font-semibold tracking-[1.5] mt-[14px]">
            {selectedTab}
          </p>
        </div>
        <button
          onClick={onClose}
          type="button"
          aria-label="Close"
          className="text-[#B77145] hover:opacity-75 text-3xl font-bold leading-none p-1 transition-opacity cursor-pointer"
        >
          <img src={cross} className="w-[24px] h-auto" />
        </button>
      </div>

      {/* Content Container */}
      <div className="relative flex-1 min-h-0 w-full overflow-hidden">
        
        <div
          ref={containerRef}
          onScroll={handleScroll}
          className="h-[50vh] sm:h-[40vh] w-full overflow-y-auto py-2 pr-2 sm:pr-4 text-[13px] sm:text-[14px] lg:text-[16px] font-medium md:font-normal leading-[1.6] text-[#424242] tracking-wide"
          style={{
            scrollbarWidth: "none",
            msOverflowStyle: "none",
          }}
        >
          <style
            dangerouslySetInnerHTML={{
              __html: `
          div::-webkit-scrollbar {
            display: none;
          }
        `,
            }}
          />

          {termsSections
            .find((section) => section.heading === selectedTab)
            ?.data.map((paragraph, index) => (
              <p key={index}>{paragraph}</p>
            ))}
        </div>
        {isOverflowing && scrollPercentage < 98 && (
          <div className="bottom-fade-overlay" />
        )}
      </div>

      {/* Footer Controls */}
      {/* Footer Controls */}
      <div className="mt-6 flex justify-between items-center pt-2 shrink-0">
        <div className="relative w-28 sm:w-36 h-2 bg-white rounded-full overflow-hidden">
          <div
            className="absolute top-0 left-0 h-full bg-[#B77145] rounded-full transition-all duration-150 ease-out"
            style={{
              width: "20px",
              left: `calc(${scrollPercentage}% - ${(scrollPercentage / 100) * 20}px)`,
            }}
          />
        </div>

        <button
          onClick={onClose}
          className="md:text-[14px] text-[10px] font-semibold text-[#B77145] rounded-[27px] md:rounded-[35px] md:min-w-[117px] min-w-[110px] h-[40px] md:h-[60px] bg-white tracking-wider cursor-pointer transition-all hover:scale-[1.02] active:scale-[1.02]"
        >
          Continue
        </button>
      </div>
    </div>
  );
}

